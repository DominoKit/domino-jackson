package org.dominokit.jackson.processor.builder;

import com.fasterxml.jackson.databind.annotation.JsonDeserialize;
import java.util.Objects;
import org.dominokit.jackson.annotation.JSONMapper;

@JsonDeserialize(builder = EmptyPrefixBeanBuilder.class)
@JSONMapper
public class EmptyPrefixBean {

  private final String id;
  private final String name;

  public EmptyPrefixBean(String id, String name) {
    this.id = id;
    this.name = name;
  }

  public String getId() {
    return id;
  }

  public String getName() {
    return name;
  }

  @Override
  public boolean equals(Object o) {
    if (this == o) return true;
    if (o == null || getClass() != o.getClass()) return false;
    EmptyPrefixBean that = (EmptyPrefixBean) o;
    return Objects.equals(id, that.id) && Objects.equals(name, that.name);
  }

  @Override
  public int hashCode() {
    return Objects.hash(id, name);
  }
}
